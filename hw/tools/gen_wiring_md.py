"""Write hardware/SCHEMATIC_WIRING_SPEC.md, the pin-by-pin wiring list, from hw/design.py.

    python -m hw.tools.gen_wiring_md
"""
from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

from hw import design
from hw.parts import PARTS

DST = Path(__file__).resolve().parents[2] / "hardware" / "SCHEMATIC_WIRING_SPEC.md"

BLOCKS = [
    ("usb", "USB-C input"),
    ("power", "Power and test pads"),
    ("mcu", "RP2354B, core regulator, crystal, BOOTSEL"),
    ("afe", "Analog front end (both channels)"),
    ("adc", "AD9288 dual ADC"),
    ("logic", "Logic pod header"),
    ("lcd", "LCD and backlight"),
    ("ui", "Buttons and work-lights"),
]
WIDE = 12   # components with more pins than this get their own pin table


def _natural(s: str):
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", s)]


def _part(c: design.Comp) -> tuple[str, str]:
    p = PARTS.get(c.part) if c.part else None
    name = (p.mpn or p.value) if p else (c.value or "-")
    return name, (p.lcsc if p else "")


def render() -> str:
    out = [
        "# ProbePen-AI wiring list",
        "",
        "Generated by `hw/tools/gen_wiring_md.py` from `hw/design.py`; do not edit by hand. Pin numbers are KiCad",
        "symbol pins and footprint pads. `NC` pins are left out of the component lists.",
        "",
        f"GPIO map: {', '.join(f'GPIO{v} {k}' for k, v in sorted(design.GPIO.items(), key=lambda kv: kv[1]))}.",
        "",
    ]
    by_block = defaultdict(list)
    for c in design.COMPONENTS:
        by_block[c.block].append(c)
    known = [b for b, _ in BLOCKS]
    blocks = BLOCKS + [(b, b) for b in sorted(by_block) if b not in known]
    wide = []
    for block, title in blocks:
        comps = sorted(by_block.get(block, []), key=lambda c: _natural(c.ref))
        if not comps:
            continue
        out += [f"## {title}", "", "| Ref | Value | Part | LCSC | Fitted | Pins |", "|---|---|---|---|---|---|"]
        for c in comps:
            name, lcsc = _part(c)
            if len(c.pins) > WIDE:
                pins = f"see the {c.ref} pin table below"
                wide.append(c)
            else:
                pins = ", ".join(f"{k}: `{v}`" for k, v in sorted(c.pins.items(), key=lambda kv: _natural(kv[0]))
                                 if v != "NC")
            out.append(f"| {c.ref} | {c.value} | {name} | {lcsc} | {'no (hand-fit)' if c.dnp else 'yes'} | {pins} |")
        out.append("")
    for c in wide:
        name, _ = _part(c)
        out += [f"## {c.ref} pins ({name})", "", "| Pin | Net | Pin | Net |", "|---|---|---|---|"]
        rows = sorted(c.pins.items(), key=lambda kv: _natural(kv[0]))
        half = (len(rows) + 1) // 2
        for i in range(half):
            a = rows[i]
            b = rows[i + half] if i + half < len(rows) else ("", "")
            out.append(f"| {a[0]} | `{a[1]}` | {b[0]} | {'`' + b[1] + '`' if b[1] else ''} |")
        out.append("")
    nets = defaultdict(list)
    for c in design.COMPONENTS:
        for pin, net in c.pins.items():
            if net != "NC":
                nets[net].append(f"{c.ref}.{pin}")
    out += ["## Nets", "", "| Net | Pins |", "|---|---|"]
    for net in sorted(nets, key=_natural):
        out.append(f"| `{net}` | {' '.join(sorted(nets[net], key=_natural))} |")
    out.append("")
    return "\n".join(out)


def main() -> None:
    DST.write_text(render(), encoding="utf8", newline="\n")
    print("wrote", DST)


if __name__ == "__main__":
    main()
