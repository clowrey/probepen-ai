from __future__ import annotations

ROUTES: dict = {}


def t(net, *pts, w=0.14, layer="F", vias=(), via=None, radii=None, start=None, end=None, cuts=None):
    d = {
        "layer": layer,
        "w": w,
        "pts": list(pts),
        "vias": list(vias),
        "radii": list(radii) if radii else None,
        "start": start,
        "end": end,
        "cuts": list(cuts) if cuts else None,
    }
    if via is not None:
        d["via"] = via
    ROUTES.setdefault(net, []).append(d)


def b(net, *pts, w=0.14, vias=(), via=None, radii=None, start=None, end=None, cuts=None):
    t(net, *pts, w=w, layer="B", vias=vias, via=via, radii=radii, start=start, end=end, cuts=cuts)


def i2(net, *pts, w=0.14, vias=(), via=None, radii=None, start=None, end=None, cuts=None):
    t(net, *pts, w=w, layer="In2", vias=vias, via=via, radii=radii, start=start, end=end, cuts=cuts)


