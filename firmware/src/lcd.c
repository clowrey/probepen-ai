uint16_t lcd_rgb565(uint8_t r, uint8_t g, uint8_t b) {
    uint16_t r5 = (uint16_t)((r >> 3u) & 0x1Fu);
    uint16_t g6 = (uint16_t)((g >> 2u) & 0x3Fu);
    uint16_t b5 = (uint16_t)((b >> 3u) & 0x1Fu);
    return (uint16_t)((r5 << 11u) | (g6 << 5u) | b5);
}

const lcd_init_cmd_t *lcd_st7735_init_seq(size_t *out_len) {
    if (out_len) {
        *out_len = sizeof(ST7735_INIT_SEQ) / sizeof(ST7735_INIT_SEQ[0]);
    }
    return ST7735_INIT_SEQ;
}

const lcd_init_cmd_t *lcd_st7789_init_seq(size_t *out_len) {
    if (out_len) {
        *out_len = sizeof(ST7789_INIT_SEQ) / sizeof(ST7789_INIT_SEQ[0]);
    }
    return ST7789_INIT_SEQ;
}

const lcd_init_cmd_t *lcd_panel_init_seq(size_t *out_len) {
#ifdef PROBEPEN_LCD_096
    return lcd_st7735_init_seq(out_len);
#else
    return lcd_st7789_init_seq(out_len);
#endif
}

void lcd_panel_init(const lcd_bus_t *bus) {
    if (!bus || !bus->write_cmd || !bus->write_data) {
        return;
    }
    size_t n = 0u;
    const lcd_init_cmd_t *seq = lcd_panel_init_seq(&n);
    for (size_t i = 0u; i < n; ++i) {
        bus->write_cmd(bus->ctx, seq[i].cmd);
        if (seq[i].len > 0u) {
            bus->write_data(bus->ctx, seq[i].data, seq[i].len);
        }
        if (seq[i].delay_ms > 0u && bus->delay_ms) {
            bus->delay_ms(bus->ctx, seq[i].delay_ms);
        }
    }
}

void lcd_panel_set_window(const lcd_bus_t *bus, uint16_t x0, uint16_t y0, uint16_t x1, uint16_t y1) {
    if (!bus || !bus->write_cmd || !bus->write_data) {
        return;
    }
    uint16_t xa = (uint16_t)(x0 + LCD_X_OFFSET), xb = (uint16_t)(x1 + LCD_X_OFFSET);
    uint16_t ya = (uint16_t)(y0 + LCD_Y_OFFSET), yb = (uint16_t)(y1 + LCD_Y_OFFSET);
    uint8_t col[4] = {(uint8_t)(xa >> 8), (uint8_t)xa, (uint8_t)(xb >> 8), (uint8_t)xb};
    uint8_t row[4] = {(uint8_t)(ya >> 8), (uint8_t)ya, (uint8_t)(yb >> 8), (uint8_t)yb};
    bus->write_cmd(bus->ctx, 0x2Au);   /* CASET */
    bus->write_data(bus->ctx, col, 4u);
    bus->write_cmd(bus->ctx, 0x2Bu);   /* RASET */
    bus->write_data(bus->ctx, row, 4u);
    bus->write_cmd(bus->ctx, 0x2Cu);   /* RAMWR */
}

void lcd_fb_clear(uint16_t *fb, uint16_t color) {
    if (!fb) {
        return;
    }
    for (size_t i = 0u; i < LCD_PIXELS; ++i) {
        fb[i] = color;
    }
}

void lcd_fb_pixel(uint16_t *fb, int x, int y, uint16_t color) {
    if (!fb || x < 0 || y < 0 || x >= (int)LCD_WIDTH || y >= (int)LCD_HEIGHT) {
        return;
    }
    fb[(size_t)y * LCD_WIDTH + (size_t)x] = color;
}

void lcd_fb_vline(uint16_t *fb, int x, int y0, int y1, uint16_t color) {
    if (!fb || x < 0 || x >= (int)LCD_WIDTH) {
        return;
    }
    if (y0 > y1) {
        int tmp = y0;
        y0 = y1;
        y1 = tmp;
    }
    if (y1 < 0 || y0 >= (int)LCD_HEIGHT) {
        return;
    }
    if (y0 < 0) {
        y0 = 0;
    }
    if (y1 >= (int)LCD_HEIGHT) {
        y1 = (int)LCD_HEIGHT - 1;
    }
    for (int y = y0; y <= y1; ++y) {
        fb[(size_t)y * LCD_WIDTH + (size_t)x] = color;
    }
}

void lcd_fb_hline(uint16_t *fb, int x0, int x1, int y, uint16_t color) {
    if (!fb || y < 0 || y >= (int)LCD_HEIGHT) {
        return;
    }
    if (x0 > x1) {
        int tmp = x0;
        x0 = x1;
        x1 = tmp;
    }
    if (x0 < 0) {
        x0 = 0;
    }
    if (x1 >= (int)LCD_WIDTH) {
        x1 = (int)LCD_WIDTH - 1;
    }
    for (int x = x0; x <= x1; ++x) {
        fb[(size_t)y * LCD_WIDTH + (size_t)x] = color;
    }
}

void lcd_fb_rect(uint16_t *fb, int x, int y, int w, int h, uint16_t color) {
    if (!fb || w <= 0 || h <= 0) {
        return;
    }
    for (int row = y; row < y + h; ++row) {
        lcd_fb_hline(fb, x, x + w - 1, row, color);
    }
}

void lcd_fb_draw_char(uint16_t *fb, int x, int y, char ch, uint16_t fg, uint16_t bg) {
    if (!fb) {
        return;
    }
    const uint8_t *rows = glyph(ch);
    for (int r = 0; r < LCD_GLYPH_H; ++r) {
        for (int c = 0; c < LCD_GLYPH_W; ++c) {
            bool on = (r < 7 && c < 5) && ((rows[r] >> (4 - c)) & 1u) != 0u;
            lcd_fb_pixel(fb, x + c, y + r, on ? fg : bg);
        }
    }
}

void lcd_fb_draw_text(uint16_t *fb, int x, int y, const char *str, uint16_t fg, uint16_t bg) {
    if (!fb || !str) {
        return;
    }
    for (int cx = x; *str != '\0'; ++str, cx += LCD_GLYPH_W) {
        lcd_fb_draw_char(fb, cx, y, *str, fg, bg);
    }
}

int lcd_fb_draw_text_scaled(uint16_t *fb, int x, int y, const char *str, int scale, uint16_t fg) {
    if (!str) {
        return x;
    }
    if (scale < 1) {
        scale = 1;
    }
    for (; *str != '\0'; ++str, x += LCD_GLYPH_W * scale) {
        const uint8_t *rows = glyph(*str);
        for (int r = 0; r < 7; ++r) {
            for (int c = 0; c < 5; ++c) {
                if (((rows[r] >> (4 - c)) & 1u) != 0u) {
                    lcd_fb_rect(fb, x + c * scale, y + r * scale, scale, scale, fg);
                }
            }
        }
    }
    return x;
}

int lcd_text_width(const char *str, int scale) {
    int n = 0;
    while (str && str[n] != '\0') {
        ++n;
    }
    return n * LCD_GLYPH_W * (scale < 1 ? 1 : scale);
}
